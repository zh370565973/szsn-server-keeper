CREATE TABLE SCHEMA_VERSION (
    VERSION INT PRIMARY KEY,
    DESCRIPTION VARCHAR(200) NOT NULL,
    CHECKSUM VARCHAR(64) NOT NULL,
    APPLIED_AT BIGINT NOT NULL
);

CREATE TABLE SYS_CONFIG (
    CONFIG_KEY VARCHAR(128) PRIMARY KEY,
    VALUE_JSON CLOB NOT NULL,
    VERSION BIGINT NOT NULL,
    UPDATED_AT BIGINT NOT NULL
);

CREATE TABLE RESOURCE_TASK (
    ID VARCHAR(36) PRIMARY KEY,
    NAME VARCHAR(64) NOT NULL,
    DESCRIPTION VARCHAR(500) NOT NULL,
    MODE VARCHAR(16) NOT NULL,
    CPU_TARGET_PCT DOUBLE,
    MEMORY_MODE VARCHAR(32),
    MEMORY_TARGET_BYTES BIGINT,
    MEMORY_TARGET_PCT DOUBLE,
    RUN_MODE VARCHAR(16) NOT NULL,
    DURATION_SECONDS BIGINT,
    VERSION BIGINT NOT NULL,
    DELETED_AT BIGINT,
    CREATED_AT BIGINT NOT NULL,
    UPDATED_AT BIGINT NOT NULL
);

CREATE TABLE TASK_SCHEDULE (
    ID VARCHAR(36) PRIMARY KEY,
    TASK_ID VARCHAR(36) NOT NULL,
    TYPE VARCHAR(32) NOT NULL,
    SCHEDULE_JSON CLOB NOT NULL,
    TIMEZONE VARCHAR(64) NOT NULL,
    ENABLED BOOLEAN NOT NULL,
    NEXT_FIRE_AT BIGINT,
    VERSION BIGINT NOT NULL,
    CREATED_AT BIGINT NOT NULL,
    UPDATED_AT BIGINT NOT NULL
);

CREATE INDEX IDX_SCHEDULE_DUE ON TASK_SCHEDULE (ENABLED, NEXT_FIRE_AT);

CREATE TABLE TASK_EXECUTION (
    ID VARCHAR(36) PRIMARY KEY,
    TASK_ID VARCHAR(36),
    SCHEDULE_ID VARCHAR(36),
    SCHEDULED_AT BIGINT,
    CONFIG_SNAPSHOT_JSON CLOB NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    REASON VARCHAR(64),
    VERSION BIGINT NOT NULL,
    STARTED_AT BIGINT,
    ENDED_AT BIGINT,
    LAST_HEARTBEAT_AT BIGINT,
    ELAPSED_DURATION_MS BIGINT,
    ACTIVE_DURATION_MS BIGINT,
    STATS_JSON CLOB,
    IDEMPOTENCY_KEY VARCHAR(64),
    REQUEST_HASH VARCHAR(128),
    REQUEST_SOURCE VARCHAR(32)
);

CREATE INDEX IDX_EXEC_STARTED ON TASK_EXECUTION (STARTED_AT);
CREATE INDEX IDX_EXEC_STATUS ON TASK_EXECUTION (STATUS);
CREATE INDEX IDX_EXEC_TASK ON TASK_EXECUTION (TASK_ID);
CREATE UNIQUE INDEX UQ_EXEC_SCHEDULE_FIRE ON TASK_EXECUTION (SCHEDULE_ID, SCHEDULED_AT);

CREATE TABLE RESOURCE_METRIC (
    BUCKET_START BIGINT PRIMARY KEY,
    SAMPLE_COUNT INT NOT NULL,
    COVERAGE_MS BIGINT NOT NULL,
    METRICS_JSON CLOB NOT NULL
);

CREATE TABLE OPERATION_LOG (
    ID VARCHAR(36) PRIMARY KEY,
    EXECUTION_ID VARCHAR(36),
    ACTOR VARCHAR(128) NOT NULL,
    SOURCE_IP VARCHAR(64),
    ACTION VARCHAR(64) NOT NULL,
    BEFORE_JSON CLOB,
    AFTER_JSON CLOB,
    RESULT VARCHAR(32) NOT NULL,
    REASON VARCHAR(500),
    REQUEST_ID VARCHAR(64),
    CREATED_AT BIGINT NOT NULL
);

CREATE INDEX IDX_LOG_CREATED ON OPERATION_LOG (CREATED_AT);
CREATE INDEX IDX_LOG_EXEC ON OPERATION_LOG (EXECUTION_ID);

CREATE TABLE REQUEST_DEDUP (
    IDEMPOTENCY_KEY VARCHAR(64) PRIMARY KEY,
    REQUEST_HASH VARCHAR(128) NOT NULL,
    EXECUTION_ID VARCHAR(36),
    CREATED_AT BIGINT NOT NULL,
    EXPIRES_AT BIGINT NOT NULL
);
